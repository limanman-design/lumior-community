import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const ids = ['mba-topic', 'mba-lit', 'mba-review', 'mba-proposal'];
const entries = await Promise.all(ids.map(async id => [id, await readFile(new URL(`skills/${id}/SKILL.md`, root), 'utf8')]));
const template = await readFile(new URL('templates/mba-thesis/settings.md', root), 'utf8');
const output = '// Generated by scripts/sync-mba-skills.mjs from the product skills/ source files.\n'
  + `export const thesisSkillContent = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`
  + `export const thesisSettingsTemplate = ${JSON.stringify(template)};\n`;
await writeFile(new URL('lib/thesis/skill-content.generated.ts', root), output);
console.log(`Bundled ${ids.length} MBA skills in ${fileURLToPath(new URL('lib/thesis/', root))}`);
