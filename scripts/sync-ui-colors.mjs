import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const palette = JSON.parse(await readFile(new URL('design-system/ui-palette.json', root), 'utf8'));
if (palette.colors.length > palette.limit) throw new Error('UI 色板超过 50 项');
if (new Set(palette.colors.map(c => c.key)).size !== palette.colors.length) throw new Error('重复的颜色用途');
const css = `/* Generated by scripts/sync-ui-colors.mjs from design-system/ui-palette.json.
   Dark UI: ${palette.colors.length} slots, including alpha colors. Content colors are separate.
   Change the palette source, then sync; do not add raw colors in components. */
:root, .dark {
${palette.colors.map(c => `  /* ${c.name} · ${c.usage} */\n  --ui-${c.key}: ${c.value};`).join('\n')}
}
`;
const target = new URL('app/ui-colors.css', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== css) throw new Error('请运行 node scripts/sync-ui-colors.mjs 同步色板');
} else await writeFile(target, css);
console.log(`${palette.colors.length} / ${palette.limit} UI color slots · ${fileURLToPath(target)}`);
